-- [1단계] 테이블 생성
CREATE TABLE IF NOT EXISTS auth_slide_guides (
  id              BIGSERIAL PRIMARY KEY,
  auth_method     TEXT NOT NULL,
  slide_number    INT NOT NULL,
  chapter         TEXT NOT NULL,
  slide_title     TEXT NOT NULL,
  action_ko       TEXT NOT NULL,
  error_cases     JSONB DEFAULT '[]',
  tips            TEXT,
  created_at      TIMESTAMPTZ DEFAULT NOW()
);

-- [2단계] 중복 방지 인덱스
CREATE UNIQUE INDEX IF NOT EXISTS idx_auth_slide_unique
  ON auth_slide_guides (auth_method, slide_number);

-- [3단계] RLS 활성화 (보안 켜기)
ALTER TABLE auth_slide_guides ENABLE ROW LEVEL SECURITY;

-- [4단계] 서비스 롤(서버)만 모든 작업 허용 (anon/클라이언트는 접근 불가)
CREATE POLICY "service_role_all" ON auth_slide_guides
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

